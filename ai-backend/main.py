def _prepare_files(payload: dict) -> list[dict]:
    """
    Normalises the WebSocket payload to a list of {name, content} dicts.
    Accepts both `{files: [...]}` (multi-file) and `{code: "..."}` (legacy).
    Also injects the matplotlib preamble into main.py.
    """
    if "files" in payload:
        files = [{"name": f["name"], "content": f["content"]} for f in payload["files"]]
    else:
        files = [{"name": "main.py", "content": payload.get("code", "")}]

    # Inject matplotlib preamble into main.py
    for f in files:
        if f["name"] == "main.py":
            f["content"] = MATPLOTLIB_PREAMBLE + f["content"]
            break

    return files


async def _install_packages_subprocess(packages: list[str], cwd: str, ws: WebSocket) -> bool:
    """Installs pip packages in the subprocess sandbox. Returns True on success."""
    pkg_list = ", ".join(packages[:5]) + ("..." if len(packages) > 5 else "")
    await ws.send_json({"trace": {"step": "Package Install", "detail": f"pip install {pkg_list}"}})
    try:
        result = await asyncio.to_thread(
            subprocess.run,
            [sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check", *packages],
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=60,
        )
        if result.returncode != 0:
            await ws.send_json({"error": f"pip install failed:\n{result.stderr}", "status": "error"})
            return False
        await ws.send_json({"output": f"[Installed: {', '.join(packages)}]\n"})
        return True
    except subprocess.TimeoutExpired:
        await ws.send_json({"error": "pip install timed out (60s)", "status": "error"})
        return False


def _write_to_tmpdir(files: list[dict]) -> str:
    """Writes files to a fresh temp directory and returns its path."""
    tmp_dir = tempfile.mkdtemp()
    for f in files:
        dest = os.path.join(tmp_dir, f["name"])
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as fp:
            fp.write(f["content"])
    return tmp_dir


def _classify_line(line: str, is_error: bool) -> dict:
    stripped = line.rstrip()
    if not is_error and PLOT_MARKER in stripped:
        return {"type": "plot", "text": stripped.split(PLOT_MARKER, 1)[1]}
    return {"type": "error" if is_error else "output", "text": line}


async def _send_queue_msg(ws: WebSocket, msg: dict) -> None:
    t = msg["type"]
    if t == "plot":
        await ws.send_json({"plot": msg["text"]})
    elif t == "error":
        await ws.send_json({"error": msg["text"]})
    else:
        await ws.send_json({"output": msg["text"]})


async def _execute_subprocess(
    files: list[dict],
    ws: WebSocket,
    packages: list[str] | None = None,
    mode: str = "run",
) -> None:
    tmp_dir = _write_to_tmpdir(files)
    try:
        if packages:
            ok = await _install_packages_subprocess(packages, tmp_dir, ws)
            if not ok:
                return

        if mode == "test":
            test_files = [f["name"] for f in files if f["name"].startswith("test_") or f["name"].endswith("_test.py")]
            if not test_files:
                await ws.send_json({"error": "No test files found. Create files named test_*.py to run tests.", "status": "error"})
                return
            cmd = [sys.executable, "-m", "pytest", "-v", "--tb=short", "--no-header", "-p", "no:cacheprovider"]
        else:
            main_path = os.path.join(tmp_dir, "main.py")
            if not os.path.exists(main_path):
                await ws.send_json({"error": "No main.py found in project files.", "status": "error"})
                return
            cmd = [sys.executable, "-u", main_path]

        process = subprocess.Popen(
            cmd,
            cwd=tmp_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
            encoding="utf-8",
            errors="replace",
        )

        out_queue: queue.Queue = queue.Queue()

        def read_stream(stream, is_error: bool = False):
            for line in iter(stream.readline, ""):
                if line:
                    out_queue.put(_classify_line(line, is_error))
            stream.close()

        t_out = threading.Thread(target=read_stream, args=(process.stdout,), daemon=True)
        t_err = threading.Thread(target=read_stream, args=(process.stderr, True), daemon=True)
        t_out.start()
        t_err.start()

        deadline = asyncio.get_event_loop().time() + EXECUTION_TIMEOUT_SECONDS
        timed_out = False

        while t_out.is_alive() or t_err.is_alive() or not out_queue.empty():
            if asyncio.get_event_loop().time() > deadline:
                process.kill()
                timed_out = True
                break
            try:
                await _send_queue_msg(ws, out_queue.get_nowait())
            except queue.Empty:
                await asyncio.sleep(0.05)

        t_out.join(timeout=2)
        t_err.join(timeout=2)
        process.wait()

        if timed_out:
            await ws.send_json({"error": f"\nExecution timed out after {EXECUTION_TIMEOUT_SECONDS}s.", "status": "error"})
        elif process.returncode != 0:
            await ws.send_json({"error": f"\nProcess exited with code {process.returncode}"})
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


async def _execute_docker(
    files: list[dict],
    ws: WebSocket,
    packages: list[str] | None = None,
    mode: str = "run",
) -> None:
    import docker  # noqa: PLC0415
    client = docker.from_env()
    out_queue: asyncio.Queue = asyncio.Queue()
    loop = asyncio.get_event_loop()
    container = None
    tmp_dir = None

    if packages:
        pkg_list = ", ".join(packages[:5]) + ("..." if len(packages) > 5 else "")
        await ws.send_json({"trace": {"step": "Package Install", "detail": f"pip install {pkg_list}"}})

    def stream_logs():
        nonlocal container, tmp_dir
        try:
            tmp_dir = _write_to_tmpdir(files)

            if mode == "test":
                test_files = [f["name"] for f in files if f["name"].startswith("test_") or f["name"].endswith("_test.py")]
                if not test_files:
                    loop.call_soon_threadsafe(out_queue.put_nowait, ("error", "No test files found. Create files named test_*.py to run tests."))
                    return
                if packages:
                    run_cmd = f"pip install -q {' '.join(packages)} && python -m pytest -v --tb=short --no-header -p no:cacheprovider"
                else:
                    run_cmd = "pip install -q pytest && python -m pytest -v --tb=short --no-header -p no:cacheprovider"
            else:
                main_path = os.path.join(tmp_dir, "main.py")
                if not os.path.exists(main_path):
                    loop.call_soon_threadsafe(out_queue.put_nowait, ("error", "No main.py found."))
                    return
                if packages:
                    run_cmd = f"pip install -q {' '.join(packages)} && python -u /sandbox/main.py"
                else:
                    run_cmd = "python -u /sandbox/main.py"

            # Use network access only when packages need installing; disable otherwise
            network = "bridge" if (packages or mode == "test") else "none"

            container = client.containers.run(
                DOCKER_IMAGE,
                ["sh", "-c", run_cmd],
                volumes={tmp_dir: {"bind": "/sandbox", "mode": "ro"}},
                mem_limit="128m",
                nano_cpus=500_000_000,
                network_mode=network,
                remove=False,
                detach=True,
                stdout=True,
                stderr=True,
            )
            for chunk in container.logs(stream=True, follow=True):
                line = chunk.decode("utf-8", errors="replace")
                stripped = line.rstrip()
                if PLOT_MARKER in stripped:
                    b64 = stripped.split(PLOT_MARKER, 1)[1]
                    loop.call_soon_threadsafe(out_queue.put_nowait, ("plot", b64))
                else:
                    loop.call_soon_threadsafe(out_queue.put_nowait, ("output", line))
            result = container.wait()
            loop.call_soon_threadsafe(out_queue.put_nowait, ("done", result["StatusCode"]))
        except Exception as e:
            loop.call_soon_threadsafe(out_queue.put_nowait, ("error", str(e)))
        finally:
            if tmp_dir:
                shutil.rmtree(tmp_dir, ignore_errors=True)
            if container:
                try:
                    container.remove(force=True)
                except Exception:
                    pass

    thread = threading.Thread(target=stream_logs, daemon=True)
    thread.start()

    deadline = loop.time() + EXECUTION_TIMEOUT_SECONDS
    timed_out = False

    while True:
        remaining = max(0.1, deadline - loop.time())
        try:
            msg_type, msg_data = await asyncio.wait_for(out_queue.get(), timeout=remaining)
        except asyncio.TimeoutError:
            timed_out = True
            if container:
                try:
                    container.kill()
                except Exception:
                    pass
            break

        if msg_type == "done":
            if msg_data != 0:
                await ws.send_json({"error": f"\nProcess exited with code {msg_data}"})
            break
        elif msg_type == "error":
            await ws.send_json({"error": msg_data, "status": "error"})
            break
        elif msg_type == "plot":
            await ws.send_json({"plot": msg_data})
        else:
            await ws.send_json({"output": msg_data})

    thread.join(timeout=2)
    if timed_out:
        await ws.send_json({"error": f"\nExecution timed out after {EXECUTION_TIMEOUT_SECONDS}s.", "status": "error"})


