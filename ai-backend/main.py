def _session_to_dict(session: DBSession) -> dict:
    return {
        "id": session.id,
        "display_name": session.display_name,
        "provider": session.provider,
        "active_module_index": session.active_module_index,
        "milestone": session.milestone,
        "active_file_name": session.active_file_name,
        "created_at": session.created_at.isoformat() if session.created_at else None,
        "updated_at": session.updated_at.isoformat() if session.updated_at else None,
        "files": [{"name": f.name, "content": f.content} for f in session.files],
        "messages": [{"role": m.role, "content": m.content, "seq": m.seq} for m in session.messages],
    }


@app.post("/api/sessions", status_code=201)
def create_session(body: SessionCreateRequest, db: DBSessionORM = Depends(get_db)):
    existing = db.get(DBSession, body.id)
    if existing:
        return _session_to_dict(existing)
    session = DBSession(
        id=body.id,
        display_name=body.display_name,
        provider=body.provider,
        active_module_index=body.active_module_index,
        milestone=body.milestone,
        active_file_name=body.active_file_name,
    )
    db.add(session)
    db.commit()
    db.refresh(session)
    return _session_to_dict(session)


@app.get("/api/sessions/{session_id}")
def get_session(session_id: str, db: DBSessionORM = Depends(get_db)):
    session = db.get(DBSession, session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")
    return _session_to_dict(session)


@app.patch("/api/sessions/{session_id}")
def patch_session(session_id: str, body: SessionMetaPatch, db: DBSessionORM = Depends(get_db)):
    session = db.get(DBSession, session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")
    if body.display_name is not None:
        session.display_name = body.display_name
    if body.provider is not None:
        session.provider = body.provider
    if body.active_module_index is not None:
        session.active_module_index = body.active_module_index
    if body.milestone is not None:
        session.milestone = body.milestone
    if body.active_file_name is not None:
        session.active_file_name = body.active_file_name
    db.commit()
    return {"ok": True}


@app.put("/api/sessions/{session_id}/files")
def upsert_files(session_id: str, body: FilesPayload, db: DBSessionORM = Depends(get_db)):
    session = db.get(DBSession, session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")
    incoming_names = {f["name"] for f in body.files}
    # Remove files that no longer exist
    for existing_file in list(session.files):
        if existing_file.name not in incoming_names:
            db.delete(existing_file)
    # Upsert
    existing_map = {f.name: f for f in session.files}
    for file_data in body.files:
        name = file_data["name"]
        content = file_data.get("content", "")
        if name in existing_map:
            existing_map[name].content = content
        else:
            db.add(DBSessionFile(session_id=session_id, name=name, content=content))
    db.commit()
    return {"ok": True}


@app.post("/api/sessions/{session_id}/messages")
def upsert_messages(session_id: str, body: MessagesPayload, db: DBSessionORM = Depends(get_db)):
    session = db.get(DBSession, session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")
    existing_seqs = {m.seq for m in session.messages}
    for msg in body.messages:
        seq = int(msg["seq"])
        if seq not in existing_seqs:
            db.add(DBChatMessage(
                session_id=session_id,
                role=str(msg["role"]),
                content=str(msg["content"]),
                seq=seq,
            ))
    db.commit()
    return {"ok": True}


